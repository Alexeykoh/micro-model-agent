// Контракт текста сообщения из композера: пользовательский текст не нормализуется.
//
// Вынесено из `composer.ts` чистым модулем (без DOM и импортов `dom.js`), чтобы
// контракт проверялся тестом без поднятия всего фронтенд-графа: `bun test`
// кеширует модули на процесс, и `dom.js` из чужого DOM-теста сделал бы
// `composer.ts` неимпортируемым. Гейт: `tests/webui/multiline-roundtrip.test.ts`.

/**
 * Текст сообщения — ровно тот, что уйдёт в модель и в ленту.
 *
 * Единственная правка — канон переводов строк (`\r\n`/`\r` → `\n`); ни `\n`,
 * ни отступы, ни пустые строки не удаляются и не склеиваются. `trim()` живёт
 * только в проверках («пусто?», «это команда?») и в пейлоад не попадает: иначе
 * вставленный markdown-промпт терял бы отступ первой строки и хвостовую пустую
 * строку.
 */
export function draftForModel(value: string): string {
  return String(value == null ? "" : value).replace(/\r\n?/g, "\n");
}
