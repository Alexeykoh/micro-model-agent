/**
 * NER без модели: ФИО и адреса по строгим формам (решение 2026-11-02 —
 * «regex + словари, только высокая уверенность»).
 *
 * Почему так: ФИО из двух слов, «Улица» в заголовке и `д.` в юридическом
 * тексте дают ложные срабатывания, а ложная маска ломает ответ модели. Поэтому:
 * - ФИО требует отчества (`…ович/…евна/…ична`) — это однозначный признак;
 * - адрес требует маркер (ул./проспект/street/…) **и** номер дома рядом.
 * Остальное (имя без отчества, адрес без номера) остаётся residual risk.
 */
import type { Finding } from "../../types";
import type { Range } from "../../normalize";
import { runRules, type PiiRule } from "./util";

/** Отчество — маркер настоящего ФИО, а не «два слова с большой буквы». */
const PATRONYMIC = /(?:ович|евич|ьевич|овна|евна|ьевна|ична|инична)$/i;

/** Маркеры улицы: русского и английского. */
const STREET = "(?:ул\\.|улица|пр-т|проспект|пер\\.|переулок|ш\\.|шоссе|наб\\.|набережная|street|st\\.|avenue|ave\\.|road|rd\\.)";

/** Маркеры дома/квартиры. */
const HOUSE = "(?:д\\.|дом|кв\\.|квартира|корп\\.|корпус|оф\\.|офис|\\bno\\.?|#)";

const RULES: readonly PiiRule[] = [
  {
    // «Иванов Иван Иванович»: три слова, последнее — отчество. Границы слов —
    // Unicode-свойства: JS `\b` не видит кириллицу как word-символ.
    kind: "fio",
    re: /(?<![\p{L}])[А-ЯЁ][а-яё]{1,}(?:-[А-ЯЁ]?[а-яё]{1,})?\s+[А-ЯЁ][а-яё]{1,}(?:-[А-ЯЁ]?[а-яё]{1,})?\s+[А-ЯЁ][а-яё]{1,}(?:-[А-ЯЁ]?[а-яё]{1,})?(?![\p{L}])/gu,
    confidence: 0.85,
    validate: (match) => PATRONYMIC.test(match.trim().split(/\s+/).pop() ?? ""),
  },
  {
    // Адрес: маркер улицы + номер дома/квартиры в пределах строки.
    kind: "address",
    re: new RegExp(`${STREET}[^\\n,;]{0,60}?\\d+[а-я]?`, "gi"),
    confidence: 0.85,
  },
  {
    // Дом+квартира без улицы («д. 5, кв. 12») — только вместе, не «д. 5» в одиночку.
    kind: "address",
    re: new RegExp(`${HOUSE}\\s*\\d+[а-я]?\\s*,\\s*${HOUSE}\\s*\\d+[а-я]?`, "gi"),
    confidence: 0.8,
  },
];

/** Находки ФИО и адресов (только уверенные формы). */
export function detectNaturalPii(text: string, excluded: readonly Range[]): Finding[] {
  if (!text) return [];
  return runRules(text, RULES, excluded);
}
