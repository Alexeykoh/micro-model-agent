/**
 * Константы агентного цикла. Вынесены из agent.ts: без магических чисел,
 * переиспользуются extracted-модулями, каждая константа несёт JSDoc-обоснование.
 */

/** Макс. доля бюджета истории под результат одного тула (по токенам). */
export const TOOL_RESULT_MAX_TOKENS_RATIO = 0.3;
/** Абсолютный потолок результата тула в символах. */
export const TOOL_RESULT_ABSOLUTE_MAX_CHARS = 15000;
/**
 * Порог качества контекста, ниже которого включается принудительная
 * компакция. См. FORCED_COMPACTION_COOLDOWN — без cooldown низкое
 * качество ретриггерит компакцию на каждой итерации.
 */
export const QUALITY_TRIGGER_THRESHOLD = 40;
/**
 * Макс. символов аргументов тула в <system-summary>. Не допускает
 * дублирования `content` из write_file поверх role:"tool" сообщения,
 * которое уже несёт результат.
 */
export const TOOL_ARGS_SUMMARY_MAX_CHARS = 240;
/**
 * Макс. длина одного строкового значения аргумента в <system-summary>.
 * Более длинные значения (content/new_string/text) заменяются на `…(N chars)`:
 * их полный текст уже присутствует в assistant-сообщении с tool_calls и в
 * role:"tool" результате, поэтому дублировать тело в сводке не нужно.
 */
export const TOOL_ARG_VALUE_MAX_CHARS = 48;
/**
 * Мин. число итераций между принудительными компакциями по качеству.
 * Без него компакция не может восстановить качество и выжигает весь
 * бюджет на компактирование (наблюдалось: 56 компакций за ~28 минут).
 */
export const FORCED_COMPACTION_COOLDOWN = 3;
/** Макс. повторов при восстановимой ошибке LLM (например, токен-лимит). */
export const MAX_LLM_ERROR_RETRIES = 2;
/** Макс. повторов при вердикте халлюцинации "retry". */
export const MAX_HALLUCINATION_RETRIES = 3;
/**
 * Макс. перепроверок заявления об успехе против свежих результатов тулов
 * (success-claim check). Одна попытка: либо модель сверяется и правит
 * формулировку, либо ответ принимается как есть (fail-open, не блок).
 */
export const MAX_CLAIM_CHECK_RETRIES = 1;
/** Порог подряд идущих неудач тулов до сообщения о восстановлении. */
export const MAX_CONSECUTIVE_TOOL_FAILURES = 5;
/**
 * Порог подряд идущих ПОЛНОСТЬЮ провальных пакетов тулов (каждый вызов —
 * неудача или tool-level блок вроде `[SECURITY BLOCKED]`) до honest-stop
 * директивы. Ниже, чем MAX_CONSECUTIVE_TOOL_FAILURES: смешанные пакеты
 * (успех + неудача) и успехи сбрасывают счётчик, поэтому срабатывание
 * означает именно топтание без прогресса (наблюдалось: qwen3.5-9b перебирал
 * python/python3/bun/pip/npx после двух блоков, не останавливаясь).
 * Plugin-level блоки (`result.blocked`, guard-rails) в счётчик не входят —
 * см. контракт ToolResult.blocked.
 */
export const MAX_CONSECUTIVE_FAILED_BATCHES = 4;
/**
 * Жёсткая остановка retry-петли: столько полностью провальных пакетов подряд
 * (директива honest-stop уже проигнорирована) — цикл прерывается с честной
 * ошибкой вместо сжигания контекста. Зазор +2 к директиве даёт модели шанс
 * остановиться самой или предложить честный ответ.
 */
export const HARD_STOP_FAILED_BATCHES = 6;
/**
 * Подряд идущие пакеты, где КАЖДЫЙ вызов дословно повторяет уже сделанный за
 * ход (имя + канонические аргументы). Детект не «нет мутации», а «нет нового
 * действия»: широкая разведка новыми файлами/паттернами прогрессирует и стрик
 * не набирает. Порог директивы «перестань повторяться — ответь».
 */
export const MAX_DUPLICATE_BATCHES = 8;
/** Жёсткий терминал: столько дублирующих пакетов подряд — форс финального ответа. */
export const HARD_STOP_DUPLICATE_BATCHES = 12;
/**
 * Мин. общих (не подряд идущих) неудач тула до записи правила в память.
 * Фиксирует системные проблемы (ENOENT у LSP, сломанный конфиг), которые
 * не всплывают по пути "5 подряд неудач".
 */
export const MIN_REPEATED_TOOL_FAILURES = 3;
/** Макс. повторов финального аудита. */
export const MAX_AUDIT_RETRIES = 3;
/** Макс. повторов пустого ответа. */
export const MAX_EMPTY_RESPONSE_RETRIES = 2;
/** Макс. повторных одинаковых тулов в режиме exit-on-complete. */
export const MAX_REPEATED_TOOL_CALLS = 2;
/**
 * Макс. повторных одинаковых тулов в интерактивном режиме до жёсткой
 * остановки. Выше, чем в exit-on-complete: сначала модель получает nudge
 * (по одному разу на каждый повтор), и только потом цикл обрывается —
 * без этого модель, игнорирующая подсказки, бесконечно повторяет один
 * и тот же вызов (наблюдалось: session_info подряд после завершения задачи).
 */
export const MAX_REPEATED_TOOL_CALLS_INTERACTIVE = 5;
/**
 * Порог цикла «перфекционизм»: столько правок одного файла (или запусков
 * одной команды) за прогон, после которых цикл подталкивает модель закрыть
 * задачу. Наблюдение ses_mthn3c2a: задача готова на итерации 13, модель ещё
 * 20+ итераций микроредактировала один файл (edit → build → read → edit…).
 */
export const MUTATION_CYCLE_NUDGE_THRESHOLD = 5;